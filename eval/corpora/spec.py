def api_page_no(resource_name: str, endpoint: str) -> int:
    """1-based page of one endpoint inside ``spec_api``."""
    r = [res["name"] for res in _RESOURCES].index(resource_name)
    e = [ep[0] for ep in _ENDPOINTS].index(endpoint)
    return r * len(_ENDPOINTS) + e + 1


def errors_page_no(resource_name: str) -> int:
    """1-based page of one resource's codes inside ``spec_errors``."""
    return [res["name"] for res in _RESOURCES].index(resource_name) + 1


