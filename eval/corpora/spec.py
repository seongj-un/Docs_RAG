# wide.py·deep.py 의 관례를 따른다. 이 assert 들이 없으면 코퍼스를 손보다가
# 실험 전제가 깨져도 아무 증상 없이 "변화 없음"이 나온다 — 이 저장소가 이미
# 두 번 당한 방식이다.

_ALL_PAGES = [(doc, i + 1, text) for doc, pages in DOCUMENTS.items() for i, text in enumerate(pages)]


def _check() -> list[tuple[str, int, str]]:
    # 1. 길이 — 고정 700토큰 창이 실제로 쪽을 쪼개야 "고정 vs 섹션"이 비교다.
    for doc, page, text in _ALL_PAGES:
        assert MIN_PAGE_CHARS <= len(text) <= MAX_PAGE_CHARS, (
            f"{doc} p{page}: {len(text)}자 — {MIN_PAGE_CHARS}~{MAX_PAGE_CHARS}자여야 한다"
        )

    # 2. 헤딩 계층 — 3단 이상이 실재해야 경로 접두사 실험이 성립한다.
    for doc, page, text in _ALL_PAGES:
        levels = {
            len(line) - len(line.lstrip("#"))
            for line in text.splitlines()
            if line.startswith("#")
        }
        assert {1, 2, 3} <= levels, f"{doc} p{page}: 헤딩 단계가 {sorted(levels)} 뿐이다"

    # 3. 표 — 표가 없으면 "표가 청크에서 깨지는가"는 관측 대상이 없다.
    for doc, page, text in _ALL_PAGES:
        rows = [line for line in text.splitlines() if line.startswith("|")]
        assert len(rows) >= 3, f"{doc} p{page}: 표 행이 {len(rows)}개뿐이다"

    # 4. 중복 표현 — 실제로 여러 쪽이 같은 문장을 써야 multi_doc 이 변별력을 갖는다.
    for sentence in _ECHO:
        hits = sum(1 for _doc, _page, text in _ALL_PAGES if sentence in text)
        assert hits >= 12, f"중복 문장이 {hits}쪽에만 있다 — 중복이 성립하지 않는다"

    # 5. 정확 일치 토큰의 고유성 — 정답 쪽이 둘이면 검색이 아니라 라벨을 잰다.
    for r, resource in enumerate(_RESOURCES):
        for e in range(len(_ENDPOINTS)):
            code = _error_code(r, e)
            hits = [(doc, page) for doc, page, text in _ALL_PAGES if code in text]
            assert len(hits) == 2, f"{code} 가 {hits} 에 걸린다 — api 1 + errors 1 이어야 한다"
            assert {doc for doc, _ in hits} == {DOC_API, DOC_ERRORS}, (
                f"{code} 가 엉뚱한 문서에 있다: {hits}"
            )
            limit = f"분당 호출 한도는 {_rate_limit(r, e)}회"
            hits = [(doc, page) for doc, page, text in _ALL_PAGES if limit in text]
            assert len(hits) == 1, f"{limit!r} 가 {hits} 에 걸린다"

    for resource in _RESOURCES:
        for field, _ftype, _desc in resource["fields"]:
            hits = [doc for doc, _page, text in _ALL_PAGES if f"| {field} |" in text]
            assert hits, f"필드 {field} 가 어느 표에도 없다"

    # 6. gold anchor — 질문이 지목한 줄이 그 쪽에 실제로 있어야 한다. 이게
    #    깨지면 build_spec 이 엉뚱한 문장을 정답 스니펫으로 만든다.
    for item in QUESTIONS:
        for doc, page, anchor in item["gold"]:
            text = DOCUMENTS[doc][page - 1]
            assert anchor in text, (
                f"{item['id']}: {doc} p{page} 에 {anchor!r} 가 없다"
            )
        assert bool(item["gold"]) == (item["type"] != "no_answer"), (
            f"{item['id']}: no_answer 만 gold 가 비어야 한다"
        )

    # 7. no_answer 문항이 정말 답이 없는지. 코퍼스를 늘리다 답을 만들어 넣으면
    #    그 문항은 영원히 "거부가 정답"이라고 거짓 보고한다.
    for item in QUESTIONS:
        if item["type"] != "no_answer":
            continue
        for word in ("졸업 사정", "등록금", "장학금", "웹훅", "XML", "기숙사"):
            if word in item["q"]:
                assert not any(word in text for _d, _p, text in _ALL_PAGES), (
                    f"{item['id']}: {word!r} 가 코퍼스에 실제로 있다"
                )

    # eval/corpora 공통 규약의 (question, gold_page, type). 한 문서 안에서
    # 답이 끝나는 문항만 싣는다 — eval/run.py 는 문서 하나만 다룬다.
    return [
        (item["q"], item["gold"][0][1], item["type"])
        for item in QUESTIONS
        if len(item["gold"]) == 1 and item["gold"][0][0] == DOC_API
    ]


