def _errors_page(r: int, resource: dict) -> str:
    lines = [
        "# 오류 코드 사전",
        f"## {resource['name']} API 오류",
        "### 요약",
        "#### 이 문서가 다루는 코드",
        "| 코드 | HTTP | 재시도 |",
    ]
    filter_name = resource["filter"][0]
    for e, (name, _m, _t, _ti) in enumerate(_ENDPOINTS):
        lines.append(
            f"| {_error_code(r, e)} | {_ERROR_HTTP[name]} | 권한이나 본문을 "
            "고치기 전에는 의미 없음 |"
        )
    lines.append(f"| {_SHARED_ERROR[0]} | {_SHARED_ERROR[1]} | 대기 후 가능 |")

    for e, (name, _method, _tail, _title) in enumerate(_ENDPOINTS):
        code = _error_code(r, e)
        reason = _ERROR_REASON[name].format(filter=filter_name, key=resource["key"])
        lines += [
            f"### {code}",
            "#### 발생 조건",
            f"{resource['name']} {name}에서 {reason} 경우에 내려간다. "
            f"HTTP 상태는 {_ERROR_HTTP[name]} 이고 응답 본문은 비어 있다.",
            "#### 대처 방법",
            # 자원 이름을 문장 앞에 박아 둔다. 템플릿만 쓰면 강의와 성적처럼
            # 같은 필터(term_code)를 쓰는 두 자원의 대처 문단이 글자 그대로
            # 같아지고, 그러면 골든셋 스니펫이 정답 쪽을 하나로 지목하지
            # 못한다.
            f"{resource['name']} {name}에서 이 코드를 받으면 "
            + _REMEDY[name].format(filter=filter_name, key=resource["key"]),
            "#### 확인 절차",
            f"먼저 응답 헤더의 X-Request-Id 를 기록한다. 그다음 같은 토큰으로 "
            f"{resource['name']} 목록 조회를 한 번 호출해 권한 범위를 확인하고, "
            "범위가 맞는데도 같은 코드가 나오면 그 식별자를 첨부해 문의한다.",
            "이 코드는 재시도로 해결되지 않는다. 자동 재시도 로직이 있다면 이 "
            "코드에서는 즉시 멈추도록 예외로 등록한다.",
        ]
    lines += [
        f"### {_SHARED_ERROR[0]}",
        "#### 대처 방법",
        "Retry-After 헤더에 적힌 초만큼 기다린 뒤 재시도한다. 헤더가 없으면 "
        "60초를 기다린다. 이 코드는 요청 자체가 잘못된 것이 아니므로 본문을 "
        "고칠 필요가 없다.",
        "### 공통 안내",
        "이 문서의 코드는 발생 조건을 적지 않고 대처 방법만 적는 경우가 없다. "
        "두 절이 모두 있어야 한 코드의 항목이 완성된 것으로 본다.",
    ]
    return "\n".join(lines)


