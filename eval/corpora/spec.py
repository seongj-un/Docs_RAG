def _error_code(r: int, e: int) -> str:
    """자원·엔드포인트마다 고유한 오류 코드.

    E4012 는 Notion W5 가 예로 든 코드 그대로다(학생 > 목록 조회). 규칙으로
    만드는 이유는 손으로 적으면 열여덟 개 중 하나가 조용히 겹치기 때문이다.
    """
    return f"E{4000 + r * 30 + e * 10 + 12}"


def _rate_limit(r: int, e: int) -> int:
    """쪽마다 다른 분당 호출 한도. 코퍼스 전체에서 고유한 숫자여야 한다."""
    return 31 + (r * 3 + e) * 7


def _page_size_max(r: int) -> int:
    return 205 + r * 11


