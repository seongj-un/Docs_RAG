"""A specification-shaped corpus: headings, exact-match tokens, tables, echoes.

**왜 또 코퍼스를 만드나.** W5 는 네 가지를 A/B 한다 — 청킹 단위(고정 700토큰
vs 헤딩 섹션), 헤딩 경로 접두사, 하이브리드, 리랭커. 그런데 이 저장소의 기존
평가 코퍼스(simple·hard·wide·golden·longchunk·deep)는 전부 **조항이 나열된
평평한 텍스트**다. 헤딩이 한 줄도 없다. 그 위에서 섹션 청킹을 켜면 섹션이
문서 전체 하나뿐이라 고정 청킹과 같은 결과가 나오고, 헤딩 접두사는 붙일
경로가 없어 아무것도 안 한다. 그렇게 나온 "변화 없음"은 결과가 아니라
**픽스처 부작용**이다.

이 저장소는 정확히 그 함정에 두 번 빠졌다.

    RERANK_MAX_CHARS  기존 코퍼스가 전부 128자 미만이라 자르기 실험이
                      불가능했는데 "품질 변화 없음"으로 결론 냈다.
                      → eval/corpora/longchunk.py 가 그 교훈으로 생겼다.
    CAND_K            기존 코퍼스가 전부 CAND_K 보다 작아 설정이 무의미했는데
                      "50→5 공짜"로 결론 냈다. 실제 길이(deep.py)로 재니
                      **결과가 뒤집혔다**(app/config.py 의 cand_k 주석).

그래서 이 코퍼스는 실험이 성립하는 데 필요한 성질을 **먼저** 갖추고 시작한다.
Notion W5 가 적은 "명세 문서의 특성" 셋에 헤딩 계층을 더한 넷이다.

1. **헤딩 계층** — ``#``/``##``/``###``/``####`` 로 3~4단 경로가 실재한다
   (``학사 관리 API 명세 > 학생 > 목록 조회 > 오류 코드``). 이게 없으면 섹션
   청킹도 경로 접두사도 실험 자체가 성립하지 않는다.
2. **정확 일치 토큰** — 필드명(``student_id``), 오류 코드(``E4012``), HTTP
   상태 코드, 분당 한도 같은 숫자. 하이브리드(BM25) 실험은 여기서 갈린다:
   dense 는 ``E4012`` 와 ``E4022`` 를 거의 구분하지 못한다.
3. **표** — 모든 쪽에 파이프 표가 둘 이상 있고, 그중 하나(``응답 헤더``)는
   일부러 쪽 끝 가까이에 둔다. 고정 700토큰 창의 경계가 대체로 그 언저리에
   떨어지기 때문이다. 실제로 ``spec_api`` 18쪽 중 **17쪽에서 고정 창이 표
   한가운데를 지나가고, 섹션 청킹은 한 번도 지나가지 않는다.** 표를 앞쪽에만
   두면 창은 늘 표 뒤에서 끊겨, Notion 이 지목한 실패 모드가 이 코퍼스에서
   한 번도 일어나지 않는다 — 그러면 또 "변화 없음"이 나온다.
4. **중복 표현** — 열여덟 개 엔드포인트가 ``_ECHO`` 세 문장을 **글자 그대로**
   공유한다. 실제 명세가 그렇고, 그래야 ``multi_doc`` 이 변별력을 갖는다:
   비슷한 쪽이 여럿일 때 정답 쪽 하나를 집어내는지가 곧 점수 차이다.
5. **길이** — 쪽당 1,400자 이상(``MIN_PAGE_CHARS``). deep.py 의 교훈이다.
   53자짜리 쪽으로 잰 숫자는 실제 문서를 설명하지 못했다. 이 코퍼스의 실측
   비율은 토큰당 약 1.9자라 1,400자면 **반드시 700토큰을 넘긴다** — 넘기지
   않으면 고정 창이 쪽을 한 번도 쪼개지 않고, "고정 vs 섹션"은 비교가 아니라
   같은 것의 두 이름이 된다. 실제로 모든 쪽이 749~905토큰이라 고정 전략은
   쪽마다 정확히 두 청크를 만든다.

**문서가 셋인 것도 의도다.** ``spec_api`` 는 오류 코드가 *언제* 나는지만
적고, *무엇을 해야 하는지*는 ``spec_errors`` 에만 있다. 그래서 "E4012 가 나면
어떻게 하나" 는 두 문서를 모두 가져와야 답이 되는 진짜 ``multi_doc`` 이다 —
``synthetic_golden`` 의 multi_doc 은 한 문서 안 두 조항이었다는 한계가
``eval/datasets/FORMAT.md`` 에 적혀 있다. ``spec_ops`` 의 변경 이력은 옛 값을
그대로 싣고 있어서, 합성 코퍼스 최초로 ``freshness`` 문항이 성립한다.

**헤딩 표기에 대한 한계.** 헤딩을 ``#`` 로 명시하는 것은 실제 PDF 에는 없는
사치다. ``page.get_text("text")`` 는 글자 크기도 굵기도 버린다. 실제 문서에
섹션 청킹을 켜려면 ``dict`` 추출로 폰트 크기·굵기를 보고 헤딩을 추정하는
단계가 **추가로** 필요하고, 그 추정에는 오차가 있다. 여기서 표기를 직접 주는
이유는 그 오차를 청킹 실험에 섞지 않기 위해서다 — 섞으면 결과가 청킹 얘기인지
헤딩 추출 얘기인지 구분할 수 없다.
"""

