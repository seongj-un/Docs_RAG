def _build_api() -> list[str]:
    return [
        _api_page(r, resource, e)
        for r, resource in enumerate(_RESOURCES)
        for e in range(len(_ENDPOINTS))
    ]


def _build_errors() -> list[str]:
    return [_errors_page(r, resource) for r, resource in enumerate(_RESOURCES)]


